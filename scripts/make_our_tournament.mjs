// Turn data/tournament_results.json into the module the Worker serves.
//   node scripts/make_our_tournament.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const input = join(root, "data", "tournament_results.json");
if (!existsSync(input)) {
  console.error(`missing ${input}; run the round robin first`);
  process.exit(1);
}

const data = JSON.parse(readFileSync(input, "utf8"));
const matches = (data.matches || []).map((match) => ({
  id: match.id,
  kind: match.kind || "group",
  a: match.a,
  b: match.b,
  deals: match.deals,
  hands: match.hands,
  mean_bb: match.mean_bb,
  ci95_bb: match.ci95_bb,
  verdict: match.verdict || "tie",
  faults_a: match.faults_a || 0,
  faults_b: match.faults_b || 0,
  finished_at: match.finished_at || 0,
}));

const payload = {
  generatedAt: Math.floor(Date.now() / 1000),
  seed: data.seed,
  deals: data.deals,
  teams: data.teams || [],
  matches,
  matrix: data.matrix || {},
};

writeFileSync(
  join(root, "src", "our_tournament_data.js"),
  "// Generated by scripts/make_our_tournament.mjs - do not edit by hand.\n" +
    `export const ourTournament = ${JSON.stringify(payload)};\n`,
  "utf8",
);
writeFileSync(
  join(root, "public", "data", "our-tournament.json"),
  JSON.stringify(payload, null, 2),
  "utf8",
);
console.log(`wrote src/our_tournament_data.js (${matches.length} matches, ${payload.teams.length} teams)`);
