// Rebuild the teams table from the verified repository map produced by
// scripts/sync_team_files.mjs. A team links to the GitHub repository where its
// model.py / pickle was actually found; teams with no verified repository link
// to their own page instead.
//
//   node scripts/make_teams_data.mjs
//
// Writes src/teams_data.js and data/all-teams.csv.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const SITE = "https://poker-arena-site.vercel.app";

const teams = JSON.parse(readFileSync(join(root, "data", "live_teams.json"), "utf8"));
let resolved = {};
try {
  resolved = JSON.parse(readFileSync(join(root, "data", "team_repos_resolved.json"), "utf8"));
} catch {
  // no verified map yet
}
try {
  const extra = JSON.parse(readFileSync(join(root, "data", "team_repos_extra.json"), "utf8"));
  resolved = { ...extra, ...resolved };
} catch {
  // no manual additions
}

// Keep the descriptions from the previous build when they exist.
let previous = [];
try {
  const text = readFileSync(join(root, "src", "teams_data.js"), "utf8");
  const start = text.indexOf("[");
  const end = text.lastIndexOf("]");
  if (start !== -1 && end !== -1) previous = JSON.parse(text.slice(start, end + 1));
} catch {
  // no previous table
}
const byTeam = new Map(previous.map((row) => [row.team, row]));

const rows = teams.map((team) => {
  const old = byTeam.get(team) || {};
  return {
    team,
    site_url: `${SITE}/#/team/${encodeURIComponent(team)}`,
    search_url: `https://github.com/search?q=${encodeURIComponent(team)}&type=repositories`,
    github_repo: resolved[team] || "",
    description: old.description || "",
  };
});

const escapeCsv = (value) => `"${String(value ?? "").replace(/"/g, '""')}"`;
const header = "team,site_url,search_url,github_repo,description";
const lines = rows.map((r) =>
  [r.team, r.site_url, r.search_url, r.github_repo, r.description].map(escapeCsv).join(","),
);
writeFileSync(join(root, "data", "all-teams.csv"), [header, ...lines].join("\n"), "utf8");

writeFileSync(
  join(root, "src", "teams_data.js"),
  "// Generated by scripts/make_teams_data.mjs - do not edit by hand.\n" +
    `export const teamsData = ${JSON.stringify(rows, null, 2)};\n`,
  "utf8",
);

const withRepo = rows.filter((r) => r.github_repo.startsWith("https://github.com/")).length;
console.log(`wrote ${rows.length} teams (${withRepo} with a verified GitHub repo)`);
