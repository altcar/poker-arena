// Fetch the live competition's final Group A board and its matches, and
// compute the standard deviation for each team from its 95% interval.
//   node scripts/fetch_live_data.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const SITE = "https://poker-arena-site.vercel.app";

// Two-sided 95% Student-t critical values for 1..29 degrees of freedom,
// copied from the organiser's evals/stats.py.
const T95 = [
  12.706, 4.303, 3.182, 2.776, 2.571, 2.447, 2.365, 2.306, 2.262, 2.228,
  2.201, 2.179, 2.160, 2.145, 2.131, 2.120, 2.110, 2.101, 2.093, 2.086,
  2.080, 2.074, 2.069, 2.064, 2.060, 2.056, 2.052, 2.048, 2.045,
];

function t95(df) {
  if (df < 1) return Infinity;
  if (df >= 30) return 1.96;
  return T95[df - 1];
}

async function main() {
  const boardResponse = await fetch(`${SITE}/data/boards/group-67.json`);
  if (!boardResponse.ok) throw new Error(`board: HTTP ${boardResponse.status}`);
  const board = await boardResponse.json();
  console.log("board keys:", Object.keys(board));
  console.log("teams:", board.teams.length);

  const pairingsResponse = await fetch(`${SITE}/data/pairings-group.json`);
  if (!pairingsResponse.ok) throw new Error(`pairings: HTTP ${pairingsResponse.status}`);
  const pairings = await pairingsResponse.json();
  console.log("matches:", pairings.length);

  // One sample per deal per match; each match has `deals` deals.
  const samples = {};
  for (const p of pairings) {
    const deals = Number(p.deals) || 0;
    samples[p.a] = (samples[p.a] || 0) + deals;
    samples[p.b] = (samples[p.b] || 0) + deals;
  }

  const teams = board.teams.map((team) => {
    const n = samples[team.team] || 0;
    let std = null;
    if (n >= 2 && team.ci95 != null && Number.isFinite(team.ci95)) {
      // ci95 = 100 * t95(n-1) * std / sqrt(n)  =>  std = ci95 * sqrt(n) / (100 * t95)
      std = (team.ci95 * Math.sqrt(n)) / (100 * t95(n - 1));
    }
    return { ...team, samples: n, std };
  });

  const payload = {
    fetchedAt: Math.floor(Date.now() / 1000),
    source: `${SITE}/data/boards/group-67.json`,
    teams,
    matrix: board.matrix || {},
  };
  writeFileSync(join(root, "public", "data", "all-teams.json"), JSON.stringify(payload, null, 2));
  writeFileSync(
    join(root, "src", "all_teams_data.js"),
    "// Generated by scripts/fetch_live_data.mjs - do not edit by hand.\n" +
      `export const allTeams = ${JSON.stringify(payload)};\n`,
  );
  console.log("wrote public/data/all-teams.json and src/all_teams_data.js");
  for (const t of teams.slice(0, 8)) {
    console.log(`  ${t.rank}. ${t.team} ${t.score?.toFixed(1)} ± ${t.ci95?.toFixed(1)} std ${t.std?.toFixed(1)} (n=${t.samples})`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
