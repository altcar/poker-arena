// Build the teams CSV from the live competition site, then search GitHub for
// each team name with the gh CLI.
//   node scripts/make_teams_csv.mjs
//
// Writes:
//   data/teams.csv       team, plan, tier, site_url, search_url, github_repo, description
//   src/teams_data.js    the same rows for the worker's /api/teams.csv

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { execFile } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const SITE = "https://poker-arena-site.vercel.app";
const TEAMS_URL = `${SITE}/data/teams.json`;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fetchTeams() {
  const response = await fetch(TEAMS_URL);
  if (!response.ok) throw new Error(`${TEAMS_URL}: HTTP ${response.status}`);
  const data = await response.json();
  return data.teams.map((t) => t.team);
}

function searchRepo(team) {
  // gh search repos returns JSON; take the first result.
  return execFileAsync("gh", [
    "search", "repos", team,
    "--limit", "3",
    "--json", "fullName,url,description,stargazersCount",
  ], { maxBuffer: 4 * 1024 * 1024 });
}

function parseJsonOutput(stdout) {
  try {
    return JSON.parse(stdout);
  } catch {
    return [];
  }
}

function escapeCsv(value) {
  return `"${String(value ?? "").replace(/"/g, '""')}"`;
}

async function main() {
  let teams;
  if (process.argv.includes("--from-cache") && existsSync(join(root, "data", "live_teams.json"))) {
    teams = JSON.parse(readFileSync(join(root, "data", "live_teams.json"), "utf8"));
  } else {
    teams = await fetchTeams();
    writeFileSync(join(root, "data", "live_teams.json"), JSON.stringify(teams, null, 2));
  }
  console.log(`found ${teams.length} teams on the live site`);

  const rows = [];
  for (let i = 0; i < teams.length; i += 1) {
    const team = teams[i];
    const siteUrl = `${SITE}/#/team/${encodeURIComponent(team)}`;
    const searchUrl = `https://github.com/search?q=${encodeURIComponent(team)}&type=repositories`;
    let repo = "";
    let description = "";
    try {
      const { stdout } = await searchRepo(team);
      const results = parseJsonOutput(stdout);
      if (results.length) {
        repo = results[0].url || "";
        description = results[0].description || "";
      }
    } catch (error) {
      console.warn(`  ${team}: gh search failed: ${error.message}`);
    }
    rows.push({ team, site_url: siteUrl, search_url: searchUrl, github_repo: repo, description });
    console.log(`  [${i + 1}/${teams.length}] ${team} -> ${repo || "(none)"}`);
    // GitHub's search API allows 30 requests/minute; stay under it.
    if (i < teams.length - 1) await sleep(2100);
  }

  const header = "team,site_url,search_url,github_repo,description";
  const lines = rows.map((r) =>
    [r.team, r.site_url, r.search_url, r.github_repo, r.description].map(escapeCsv).join(","),
  );
  writeFileSync(join(root, "data", "teams.csv"), [header, ...lines].join("\n"), "utf8");

  writeFileSync(
    join(root, "src", "teams_data.js"),
    "// Generated by scripts/make_teams_csv.mjs - do not edit by hand.\n" +
      `export const teamsData = ${JSON.stringify(rows, null, 2)};\n`,
    "utf8",
  );
  console.log(`wrote data/teams.csv and src/teams_data.js (${rows.length} rows)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
