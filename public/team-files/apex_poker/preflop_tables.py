def get_hand_key(hand) -> str:
    """Converts a 2-card hand into canonical 169 string (e.g. 'AKs', 'AA', '72o')."""
    c1, c2 = hand[0], hand[1]
    if c1.value < c2.value:
        c1, c2 = c2, c1
    if c1.rank == c2.rank:
        return f"{c1.rank}{c2.rank}"
    if c1.suit == c2.suit:
        return f"{c1.rank}{c2.rank}s"
    return f"{c1.rank}{c2.rank}o"


def get_preflop_equity(hand) -> float:
    key = get_hand_key(hand)
    return HAND_EQUITY.get(key, 0.5)


def get_preflop_percentile(hand) -> float:
    key = get_hand_key(hand)
    return HAND_PERCENTILE.get(key, 0.5)
